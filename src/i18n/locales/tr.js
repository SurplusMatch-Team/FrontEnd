function mergeLocale(base, patch) {
  if (base == null) return patch;
  if (patch == null) return base;
  if (Array.isArray(patch)) return patch;
  if (typeof patch !== "object" || typeof base !== "object") return patch;
  const out = { ...base };
  for (const key of Object.keys(patch)) {
    const pv = patch[key];
    const bv = base[key];
    if (
      pv != null &&
      typeof pv === "object" &&
      !Array.isArray(pv) &&
      bv != null &&
      typeof bv === "object" &&
      !Array.isArray(bv)
    ) {
      out[key] = mergeLocale(bv, pv);
    } else {
      out[key] = pv;
    }
  }
  return out;
}

